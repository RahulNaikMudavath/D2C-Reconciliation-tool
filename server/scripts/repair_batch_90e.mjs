import prisma from '../src/config/database.js';
import { normalizeColumns } from '../src/imports/normalizers/columnNormalizer.js';
import { parseDateSafe, parseDecimalSafe } from '../src/imports/validators/importValidator.js';
import Decimal from 'decimal.js';

const BATCH_ID = '90e37661-9ed8-479c-92b6-61981bda2cc7';

export async function runDryRun() {
  console.log(`=== DRY-RUN REPAIR FOR BATCH ${BATCH_ID} ===\n`);

  // 1. Fetch batch & source records
  const batch = await prisma.importBatch.findUnique({
    where: { id: BATCH_ID },
  });

  if (!batch) {
    throw new Error(`Batch ${BATCH_ID} not found.`);
  }

  const sourceRecords = await prisma.sourceRecord.findMany({
    where: { importBatchId: BATCH_ID },
    orderBy: { rowNumber: 'asc' },
  });

  console.log(`Fetched ${sourceRecords.length} source records for batch ${batch.fileName}`);

  // 2. Fetch existing orders from database
  const rawRecords = sourceRecords.map((sr) => sr.rawData);
  const { columnMapping, normalizedRecords } = normalizeColumns(rawRecords, 'ORDERS');

  console.log('\nNew Column Mapping generated by updated normalizer:');
  console.log(columnMapping);

  // Extract order numbers
  const orderNumbers = [];
  for (const r of normalizedRecords) {
    if (r.orderNumber) orderNumbers.push(r.orderNumber);
  }

  const existingOrders = await prisma.order.findMany({
    where: { orderNumber: { in: orderNumbers } },
  });

  const existingOrderMap = new Map();
  for (const o of existingOrders) {
    existingOrderMap.set(o.orderNumber, o);
  }

  console.log(`Found ${existingOrders.length} existing Order records matching source order numbers.`);

  // 3. Analyze changes
  let expectedSettlementPopulateCount = 0;
  let weightKgPopulateCount = 0;
  let orderDateChangeCount = 0;
  let settlementDueAtChangeCount = 0;
  let newExpectedSettlementTotal = new Decimal(0);
  let orderValueTotal = new Decimal(0);

  const samples = [];
  const updatePayloads = [];

  for (let i = 0; i < sourceRecords.length; i++) {
    const sr = sourceRecords[i];
    const norm = normalizedRecords[i];
    const existing = existingOrderMap.get(norm.orderNumber);

    if (!existing) continue;

    // Parse values using corrected parsers
    const newExpectedSettlement = parseDecimalSafe(norm.expectedSettlementAmount);
    const newWeightKg = parseDecimalSafe(norm.weightKg);
    const newOrderDate = parseDateSafe(norm.orderDate);
    const newSettlementDueAt = parseDateSafe(norm.settlementDueAt);
    const newOrderValue = parseDecimalSafe(norm.orderValue);

    if (newExpectedSettlement) {
      newExpectedSettlementTotal = newExpectedSettlementTotal.plus(newExpectedSettlement);
    }
    if (newOrderValue) {
      orderValueTotal = orderValueTotal.plus(newOrderValue);
    }

    let willChangeExpectedSettlement = false;
    let willChangeWeight = false;
    let willChangeOrderDate = false;
    let willChangeSettlementDue = false;

    if (existing.expectedSettlementAmount === null && newExpectedSettlement !== null) {
      expectedSettlementPopulateCount++;
      willChangeExpectedSettlement = true;
    }

    if (existing.weightKg === null && newWeightKg !== null) {
      weightKgPopulateCount++;
      willChangeWeight = true;
    }

    if (
      newOrderDate &&
      (!existing.orderDate || existing.orderDate.getTime() !== newOrderDate.getTime())
    ) {
      orderDateChangeCount++;
      willChangeOrderDate = true;
    }

    if (
      newSettlementDueAt &&
      (!existing.settlementDueAt || existing.settlementDueAt.getTime() !== newSettlementDueAt.getTime())
    ) {
      settlementDueAtChangeCount++;
      willChangeSettlementDue = true;
    }

    updatePayloads.push({
      orderId: existing.id,
      orderNumber: existing.orderNumber,
      sourceRecordId: sr.id,
      expectedSettlementAmount: newExpectedSettlement ? newExpectedSettlement.toNumber() : null,
      weightKg: newWeightKg ? newWeightKg.toNumber() : null,
      orderDate: newOrderDate,
      settlementDueAt: newSettlementDueAt,
      newNormalizedData: norm,
    });

    if (samples.length < 3) {
      samples.push({
        orderNumber: existing.orderNumber,
        before: {
          expectedSettlementAmount: existing.expectedSettlementAmount,
          weightKg: existing.weightKg,
          orderDate: existing.orderDate ? existing.orderDate.toISOString() : null,
          settlementDueAt: existing.settlementDueAt ? existing.settlementDueAt.toISOString() : null,
        },
        after: {
          expectedSettlementAmount: newExpectedSettlement ? newExpectedSettlement.toFixed(2) : null,
          weightKg: newWeightKg ? newWeightKg.toFixed(3) : null,
          orderDate: newOrderDate ? newOrderDate.toISOString() : null,
          settlementDueAt: newSettlementDueAt ? newSettlementDueAt.toISOString() : null,
        },
      });
    }
  }

  console.log('\n=== DRY-RUN CHANGE SUMMARY ===');
  console.log(`Total Records to Update: ${updatePayloads.length} / ${sourceRecords.length}`);
  console.log(`expectedSettlementAmount to populate (from null): ${expectedSettlementPopulateCount}`);
  console.log(`weightKg to populate (from null): ${weightKgPopulateCount}`);
  console.log(`orderDate corrected timestamps: ${orderDateChangeCount}`);
  console.log(`settlementDueAt corrected timestamps: ${settlementDueAtChangeCount}`);

  console.log(`\nFinancial Aggregates Verification:`);
  console.log(`New Expected Settlement Sum: ₹${newExpectedSettlementTotal.toFixed(2)} (Target: ₹9,38,11,927.62)`);
  console.log(`Order Value Sum: ₹${orderValueTotal.toFixed(2)} (Target: ₹10,41,38,274.61)`);
  console.log(`Settlement Sum Matches Target: ${newExpectedSettlementTotal.toFixed(2) === '93811927.62'}`);

  console.log('\nSample Before / After Records (3 records):');
  console.log(JSON.stringify(samples, null, 2));

  return {
    sourceRecordsCount: sourceRecords.length,
    existingOrdersCount: existingOrders.length,
    updatePayloads,
    expectedSettlementPopulateCount,
    weightKgPopulateCount,
    orderDateChangeCount,
    settlementDueAtChangeCount,
    newExpectedSettlementTotal: newExpectedSettlementTotal.toFixed(2),
    orderValueTotal: orderValueTotal.toFixed(2),
    samples,
  };
}

export async function executeRepair(dryRunResult, userId = null) {
  console.log(`\n=== EXECUTING REPAIR ON BATCH ${BATCH_ID} ===`);
  const payloads = dryRunResult.updatePayloads;
  const t0 = performance.now();

  // 1. Update Order records in chunks of 2,000 using Prisma transaction or bulk SQL
  const CHUNK_SIZE = 2000;
  for (let i = 0; i < payloads.length; i += CHUNK_SIZE) {
    const chunk = payloads.slice(i, i + CHUNK_SIZE);
    
    // Build parameterized multi-row update query for extreme speed and safety
    // Using prisma.$transaction with batched updates
    await prisma.$transaction(
      chunk.map((item) =>
        prisma.order.update({
          where: { id: item.orderId },
          data: {
            expectedSettlementAmount: item.expectedSettlementAmount,
            weightKg: item.weightKg,
            orderDate: item.orderDate,
            settlementDueAt: item.settlementDueAt,
          },
        })
      )
    );
    console.log(`Updated orders ${i + 1} to ${Math.min(i + CHUNK_SIZE, payloads.length)}`);
  }

  // 2. Update SourceRecord normalizedData in chunks
  for (let i = 0; i < payloads.length; i += CHUNK_SIZE) {
    const chunk = payloads.slice(i, i + CHUNK_SIZE);
    await prisma.$transaction(
      chunk.map((item) =>
        prisma.sourceRecord.update({
          where: { id: item.sourceRecordId },
          data: {
            normalizedData: item.newNormalizedData,
          },
        })
      )
    );
  }

  // 3. Record AuditLog entry
  let auditUserId = userId;
  if (!auditUserId) {
    const admin = await prisma.user.findFirst({
      where: { role: { in: ['FINANCE_EXECUTIVE', 'CO_FOUNDER'] } },
    });
    auditUserId = admin?.id;
  }

  if (auditUserId) {
    await prisma.auditLog.create({
      data: {
        action: 'BATCH_IMPORT_REPAIRED',
        entity: 'ImportBatch',
        entityId: BATCH_ID,
        userId: auditUserId,
        details: {
          batchId: BATCH_ID,
          fileName: 'reconcilex_test_20k_orders_alt_headers.csv',
          repairedOrdersCount: payloads.length,
          expectedSettlementSum: dryRunResult.newExpectedSettlementTotal,
          orderValueSum: dryRunResult.orderValueTotal,
          repairedFields: ['expectedSettlementAmount', 'weightKg', 'orderDate', 'settlementDueAt'],
          timestamp: new Date().toISOString(),
        },
      },
    });
  }

  const t1 = performance.now();
  console.log(`\nRepair completed successfully in ${((t1 - t0) / 1000).toFixed(2)}s!`);
}

// Check command line arg
const isExecute = process.argv.includes('--execute');

async function main() {
  const result = await runDryRun();
  if (isExecute) {
    await executeRepair(result);
  } else {
    console.log('\n[INFO] Dry-run completed. To execute the changes, run with --execute.');
  }
}

main().catch(console.error).finally(() => process.exit(0));

